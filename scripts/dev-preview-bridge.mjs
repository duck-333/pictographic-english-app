import { createServer } from 'node:http'
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises'
import { createReadStream } from 'node:fs'
import { extname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = fileURLToPath(new URL('.', import.meta.url))
const rootDir = resolve(__dirname, '..')
const port = Number(process.env.PICTO_PREVIEW_BRIDGE_PORT || 8787)
// Development-only bridge: this local server feeds WeChat DevTools previews and must not be used in production.
const dataJsonPath = join(rootDir, 'content-seed', 'dev-preview-words.json')
const generatedDataPath = join(rootDir, 'miniapp-uni', 'word-app1', 'common', 'dev-preview-data.js')
const videoDir = join(rootDir, 'content-seed', 'dev-preview-videos')
const maxBodyBytes = Number(process.env.PICTO_PREVIEW_BRIDGE_MAX_MB || 320) * 1024 * 1024

function sendJson(response, statusCode, payload) {
  response.writeHead(statusCode, {
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Methods': 'GET,POST,OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type',
    'Content-Type': 'application/json; charset=utf-8'
  })
  response.end(JSON.stringify(payload))
}

function sendText(response, statusCode, text) {
  response.writeHead(statusCode, {
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Methods': 'GET,POST,OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type',
    'Content-Type': 'text/plain; charset=utf-8'
  })
  response.end(text)
}

function safeFileName(value, fallback = 'video.mp4') {
  const clean = String(value || fallback)
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, '-')
    .replace(/^-+|-+$/g, '')
  return clean || fallback
}

function toDataUrlParts(dataUrl) {
  const match = String(dataUrl || '').match(/^data:([^;,]+)?(;base64)?,(.*)$/)
  if (!match) return null
  return {
    mimeType: match[1] || 'video/mp4',
    isBase64: Boolean(match[2]),
    payload: match[3] || ''
  }
}

function videoContentType(filePath) {
  const ext = extname(filePath).toLowerCase()
  if (ext === '.webm') return 'video/webm'
  if (ext === '.mov') return 'video/quicktime'
  if (ext === '.m4v') return 'video/x-m4v'
  return 'video/mp4'
}

function toVideoExtension(mimeType, fileName) {
  const existing = extname(fileName || '').toLowerCase()
  if (existing) return existing
  if (mimeType === 'video/webm') return '.webm'
  if (mimeType === 'video/quicktime') return '.mov'
  if (mimeType === 'video/x-m4v') return '.m4v'
  return '.mp4'
}

function normalizeWordsPayload(raw) {
  if (Array.isArray(raw)) return { words: raw }
  if (raw && Array.isArray(raw.words)) return { words: raw.words }
  return { words: [] }
}

async function readPreviewWords() {
  try {
    const raw = await readFile(dataJsonPath, 'utf8')
    return normalizeWordsPayload(JSON.parse(raw)).words
  } catch (error) {
    if (error && error.code === 'ENOENT') return []
    throw error
  }
}

async function writePreviewWords(words) {
  await mkdir(join(rootDir, 'content-seed'), { recursive: true })
  await writeFile(dataJsonPath, `${JSON.stringify({ words }, null, 2)}\n`, 'utf8')
  const moduleSource = [
    '// Generated by scripts/dev-preview-bridge.mjs during local preview sync.',
    '// Do not hand-edit this file; use the admin preview sync button instead.',
    `export const DEV_PREVIEW_WORDS = ${JSON.stringify(words, null, 2)}`,
    ''
  ].join('\n')
  await writeFile(generatedDataPath, moduleSource, 'utf8')
}

async function saveRuntimeAsset(asset, wordId) {
  const dataUrl = asset && asset.dataUrl
  const parts = toDataUrlParts(dataUrl)
  if (!parts) return null

  await mkdir(videoDir, { recursive: true })
  const clipId = safeFileName(asset.clipId || 'clip', 'clip')
  const sourceName = safeFileName(asset.fileName || `${clipId}.mp4`, `${clipId}.mp4`)
  const ext = toVideoExtension(parts.mimeType, sourceName)
  const base = safeFileName(`${wordId || 'word'}-${clipId}`.replace(/\.[a-z0-9]+$/i, ''), 'preview-video')
  const fileName = `${base}${ext}`
  const targetPath = join(videoDir, fileName)
  const buffer = parts.isBase64
    ? Buffer.from(parts.payload, 'base64')
    : Buffer.from(decodeURIComponent(parts.payload))

  await writeFile(targetPath, buffer)

  return {
    clipId: asset.clipId,
    fileName,
    mimeType: parts.mimeType,
    size: buffer.length,
    // 127.0.0.1 is intentionally local-only; production video URLs must come from cloud/object storage over HTTPS.
    url: `http://127.0.0.1:${port}/videos/${encodeURIComponent(fileName)}`,
    storagePath: `content-seed/dev-preview-videos/${fileName}`
  }
}

function cleanClipForMiniapp(clip, savedAsset) {
  const next = { ...(clip || {}) }
  delete next.localPreviewUrl
  delete next.local_preview_url
  delete next.devVideoDataUrl
  delete next.dataUrl

  if (savedAsset) {
    next.url = savedAsset.url
    next.videoUrl = savedAsset.url
    next.storagePath = savedAsset.storagePath
    next.fileName = savedAsset.fileName
    next.mimeType = savedAsset.mimeType
    next.size = savedAsset.size
    next.provider = 'local-preview-bridge'
    next.uploadStatus = 'dev-preview-ready'
  }

  return next
}

async function buildMiniappWord(payload) {
  const rawWord = payload && payload.word ? payload.word : {}
  const wordId = String(rawWord.id || rawWord.word || 'word').trim()
  const runtimeAssets = Array.isArray(payload.runtimeAssets) ? payload.runtimeAssets : []
  const savedAssets = []

  for (const asset of runtimeAssets) {
    const saved = await saveRuntimeAsset(asset, wordId)
    if (saved) savedAssets.push(saved)
  }

  const assetByClipId = new Map(savedAssets.map((asset) => [String(asset.clipId || ''), asset]))
  const rawClips = Array.isArray(rawWord.videoClips) ? rawWord.videoClips : []
  const videoClips = rawClips.map((clip, index) => {
    const key = String(clip && (clip.clipId || clip.clip_id || `clip-${index + 1}`))
    return cleanClipForMiniapp(clip, assetByClipId.get(key))
  })

  const nextWord = {
    ...rawWord,
    videoClips,
    video: videoClips.length ? { ...(rawWord.video || {}), ...videoClips[0] } : rawWord.video
  }

  delete nextWord.localPreviewUrl
  delete nextWord.local_preview_url
  return nextWord
}

async function handleSyncWord(request, response) {
  let size = 0
  const chunks = []

  request.on('data', (chunk) => {
    size += chunk.length
    if (size > maxBodyBytes) {
      request.destroy(new Error('Payload too large'))
      return
    }
    chunks.push(chunk)
  })

  request.on('error', (error) => {
    sendJson(response, 413, { ok: false, message: error.message || 'Request failed' })
  })

  request.on('end', async () => {
    try {
      const payload = JSON.parse(Buffer.concat(chunks).toString('utf8') || '{}')
      const nextWord = await buildMiniappWord(payload)
      if (!nextWord.id || !nextWord.word) {
        sendJson(response, 400, { ok: false, message: 'word.id and word.word are required' })
        return
      }

      const words = await readPreviewWords()
      const nextWords = words.filter((item) => item && item.id !== nextWord.id && item.word !== nextWord.word)
      nextWords.unshift(nextWord)
      await writePreviewWords(nextWords)

      sendJson(response, 200, {
        ok: true,
        wordId: nextWord.id,
        word: nextWord.word,
        clipCount: Array.isArray(nextWord.videoClips) ? nextWord.videoClips.length : 0,
        generatedDataPath,
        dataJsonPath
      })
    } catch (error) {
      sendJson(response, 500, { ok: false, message: error.message || 'Sync failed' })
    }
  })
}

async function handleVideo(request, response, pathname) {
  const fileName = safeFileName(decodeURIComponent(pathname.replace(/^\/videos\//, '')), '')
  if (!fileName) {
    sendText(response, 404, 'Missing video file')
    return
  }
  const filePath = join(videoDir, fileName)
  let fileStats
  try {
    fileStats = await stat(filePath)
  } catch (error) {
    sendText(response, 404, 'Video not found')
    return
  }

  const range = request.headers.range
  const contentType = videoContentType(filePath)
  if (!range) {
    response.writeHead(200, {
      'Access-Control-Allow-Origin': '*',
      'Accept-Ranges': 'bytes',
      'Content-Length': fileStats.size,
      'Content-Type': contentType
    })
    createReadStream(filePath).pipe(response)
    return
  }

  const match = String(range).match(/bytes=(\d*)-(\d*)/)
  if (!match) {
    response.writeHead(416, {
      'Access-Control-Allow-Origin': '*',
      'Content-Range': `bytes */${fileStats.size}`
    })
    response.end()
    return
  }

  const start = match[1] ? Number(match[1]) : 0
  const requestedEnd = match[2] ? Number(match[2]) : fileStats.size - 1
  const end = Math.min(requestedEnd, fileStats.size - 1)
  if (Number.isNaN(start) || Number.isNaN(requestedEnd) || start > end || start >= fileStats.size) {
    response.writeHead(416, {
      'Access-Control-Allow-Origin': '*',
      'Content-Range': `bytes */${fileStats.size}`
    })
    response.end()
    return
  }

  response.writeHead(206, {
    'Access-Control-Allow-Origin': '*',
    'Accept-Ranges': 'bytes',
    'Content-Length': end - start + 1,
    'Content-Range': `bytes ${start}-${end}/${fileStats.size}`,
    'Content-Type': contentType
  })
  createReadStream(filePath, { start, end }).pipe(response)
}

const server = createServer((request, response) => {
  const { pathname } = new URL(request.url || '/', `http://${request.headers.host || '127.0.0.1'}`)

  if (request.method === 'OPTIONS') {
    sendText(response, 204, '')
    return
  }
  if (request.method === 'GET' && pathname === '/status') {
    sendJson(response, 200, { ok: true, port, generatedDataPath, dataJsonPath, videoDir })
    return
  }
  if (request.method === 'GET' && pathname.startsWith('/videos/')) {
    handleVideo(request, response, pathname).catch((error) => {
      sendText(response, 500, error.message || 'Video failed')
    })
    return
  }
  if (request.method === 'POST' && pathname === '/sync-word') {
    handleSyncWord(request, response)
    return
  }

  sendJson(response, 404, { ok: false, message: 'Not found' })
})

server.listen(port, '127.0.0.1', () => {
  console.log(`Pictographic preview bridge running at http://127.0.0.1:${port}`)
  console.log(`- POST /sync-word from the admin preview button`)
  console.log(`- Generated miniapp data: ${generatedDataPath}`)
})
