function extractCreateTableStatement(sql, tableName) {
  const expression = new RegExp(
    'CREATE TABLE IF NOT EXISTS `' + tableName + '` \\(([\\s\\S]*?)\\n\\) ENGINE=InnoDB[^\\n]*\\nCOMMENT=\'[^\']*\';'
  )
  const match = sql.match(expression)
  assert(match, `missing CREATE TABLE statement for ${tableName}`)
  return match[0]
}

function extractAllCreateTableStatements(sql) {
  return REQUIRED_TABLES.map((tableName) => extractCreateTableStatement(sql, tableName))
}

async function inspectCodesSchema(connection, databaseName) {
  const requiredColumns = [
    'id', 'application_id', 'generation_no', 'code_hash', 'code_hash_version', 'status',
    'active_application_id', 'issue_idempotency_key', 'replacement_code_id'
  ]
  const requiredIndexes = [
    'uk_book_benefit_codes_hash',
    'uk_book_benefit_codes_application_generation',
    'uk_book_benefit_codes_issue_idempotency',
    'uk_book_benefit_codes_replacement',
    'uk_book_benefit_codes_active_application'
  ]
  const [columnRows] = await connection.execute(
    `SELECT COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS
      WHERE TABLE_SCHEMA = ? AND TABLE_NAME = 'book_benefit_codes'`,
    [databaseName]
  )
  const [indexRows] = await connection.execute(
    `SELECT DISTINCT INDEX_NAME FROM INFORMATION_SCHEMA.STATISTICS
      WHERE TABLE_SCHEMA = ? AND TABLE_NAME = 'book_benefit_codes'`,
    [databaseName]
  )
  const columns = new Set(columnRows.map((row) => row.COLUMN_NAME))
  const indexes = new Set(indexRows.map((row) => row.INDEX_NAME))
  return {
    missingColumns: requiredColumns.filter((column) => !columns.has(column)),
    missingIndexes: requiredIndexes.filter((index) => !indexes.has(index))
  }
}

async function runCompleteMigrationTest(config, databaseName, migration001, migration007) {
  const connection = await createDatabaseConnection(config, databaseName)
  try {
    await connection.query(migration001)
    await connection.query(
      `INSERT INTO user_phone_bindings
        (user_id, phone_hash, phone_masked, hash_version, country_code, status)
       VALUES
        (101, ?, '100****0001', 'v1', '86', 'active'),
        (102, ?, '100****0002', 'v1', '86', 'active')`,
      ['a'.repeat(64), 'b'.repeat(64)]
    )
    const beforeRows = await getExistingPhoneRows(connection)
    assert.equal(beforeRows.length, 2)

    const beforePreflight = await getPhoneBindingPreflight(connection, databaseName)
    assert.equal(beforePreflight.columns.length, 0)
    assert.equal(beforePreflight.indexes.length, 0)

    await connection.query(migration007)
    await assertRequiredTables(connection, databaseName)

    const afterPreflight = await getPhoneBindingPreflight(connection, databaseName)
    assert.deepEqual(
      afterPreflight.columns.map((row) => [row.COLUMN_NAME, String(row.COLUMN_TYPE).toLowerCase(), row.IS_NULLABLE]),
      [
        ['campaign_phone_hash_version', 'varchar(16)', 'YES'],
        ['campaign_phone_identity_hash', 'binary(32)', 'YES']
      ]
    )
    assert.equal(afterPreflight.indexes.length, 1)
    assert.equal(afterPreflight.indexes[0].INDEX_NAME, 'idx_user_phone_bindings_campaign_identity')
    assert.equal(afterPreflight.indexes[0].COLUMN_NAME, 'campaign_phone_identity_hash')
    assert.equal(Number(afterPreflight.indexes[0].NON_UNIQUE), 1)

    const [campaignIdentityIndexes] = await connection.execute(
      `SELECT INDEX_NAME, NON_UNIQUE
         FROM INFORMATION_SCHEMA.STATISTICS
        WHERE TABLE_SCHEMA = ? AND TABLE_NAME = 'user_phone_bindings'
          AND COLUMN_NAME = 'campaign_phone_identity_hash'`,
      [databaseName]
    )
    assert.equal(campaignIdentityIndexes.length, 1)
    assert.equal(Number(campaignIdentityIndexes[0].NON_UNIQUE), 1)

    const afterRows = await getExistingPhoneRows(connection)
    assert.deepEqual(afterRows, beforeRows, '007 changed existing user_phone_bindings values')
    const [newColumnRows] = await connection.query(
      `SELECT campaign_phone_identity_hash, campaign_phone_hash_version
         FROM user_phone_bindings ORDER BY id`
    )
    assert(newColumnRows.every((row) =>
      row.campaign_phone_identity_hash === null && row.campaign_phone_hash_version === null
    ))

    const applications = await testApplicationConstraints(connection)
    const codes = await testCodeConstraints(connection, applications)
    await testRedemptionConstraints(connection, applications, codes)

    const [forbiddenBusinessTables] = await connection.execute(
      `SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES
        WHERE TABLE_SCHEMA = ?
          AND TABLE_NAME IN ('user_entitlements', 'entitlement_transactions', 'membership_grants')`,
      [databaseName]
    )
    assert.equal(forbiddenBusinessTables.length, 0, '007 created membership or entitlement business tables')

    const secondPreflight = await getPhoneBindingPreflight(connection, databaseName)
    assert.equal(secondPreflight.columns.length, 2)
    assert.equal(secondPreflight.indexes.length, 1)
    assert.equal(Number(secondPreflight.indexes[0].NON_UNIQUE), 1)

    for (const createStatement of extractAllCreateTableStatements(migration007)) {
      await connection.query(createStatement)
    }
    await assertRequiredTables(connection, databaseName)

    return {
      beforePhoneBindingRows: beforeRows.length,
      afterPhoneBindingRows: afterRows.length,
      preflightBefore: { columns: beforePreflight.columns.length, indexes: beforePreflight.indexes.length },
      preflightAfter: {
        columns: secondPreflight.columns.length,
        indexes: secondPreflight.indexes.length,
        nonUnique: Number(secondPreflight.indexes[0].NON_UNIQUE)
      },
      fiveTablesPresent: true,
      constraintsVerified: true,
      repeatedCreateStatementsVerified: true
    }
  } finally {
    await connection.end()
  }
}

async function runPartialTableTest(config, databaseName, migration001, migration007) {
  const connection = await createDatabaseConnection(config, databaseName)
  try {
    await connection.query(migration001)
    await connection.query(
      `CREATE TABLE book_benefit_codes (
        id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
        application_id BIGINT UNSIGNED NOT NULL,
        PRIMARY KEY (id)
      ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`
    )
    await connection.query(extractCreateTableStatement(migration007, 'book_benefit_codes'))
    const acceptance = await inspectCodesSchema(connection, databaseName)
    assert(acceptance.missingColumns.includes('code_hash'))
    assert(acceptance.missingColumns.includes('active_application_id'))
    assert(acceptance.missingIndexes.includes('uk_book_benefit_codes_active_application'))
    return {
      partialTableRiskDetected: true,
      missingColumnCount: acceptance.missingColumns.length,
      missingIndexCount: acceptance.missingIndexes.length
    }
  } finally {
    await connection.end()
  }
}

