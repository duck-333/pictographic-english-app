function readTestConfig(env = process.env) {
  const host = String(env.BOOK_BENEFIT_TEST_DB_HOST || '').trim()
  const rawPort = String(env.BOOK_BENEFIT_TEST_DB_PORT || '').trim()
  const user = String(env.BOOK_BENEFIT_TEST_DB_USER || '').trim()
  const password = String(env.BOOK_BENEFIT_TEST_DB_PASSWORD || '')
  const allowDestructive = String(env.BOOK_BENEFIT_TEST_ALLOW_DESTRUCTIVE || '').trim()

  assert.equal(host, EXPECTED_HOST, `integration test host must be exactly ${EXPECTED_HOST}`)
  assert.equal(rawPort, String(EXPECTED_PORT), `integration test port must be exactly ${EXPECTED_PORT}`)
  assert(user, 'BOOK_BENEFIT_TEST_DB_USER is required')
  assert(password, 'BOOK_BENEFIT_TEST_DB_PASSWORD is required')
  assert.equal(
    allowDestructive,
    EXPECTED_ALLOW_DESTRUCTIVE,
    'BOOK_BENEFIT_TEST_ALLOW_DESTRUCTIVE confirmation does not match'
  )

  return {
    host,
    port: EXPECTED_PORT,
    user,
    password,
    allowDestructive
  }
}

function quoteIdentifier(value) {
  assert.match(value, SAFE_DATABASE_PATTERN, 'unsafe test database identifier')
  return `\`${value}\``
}

function binaryValue(seed) {
  return crypto.createHash('sha256').update(`book-benefit-test:${seed}`).digest()
}

async function expectDuplicate(label, action) {
  let caught = null
  try {
    await action()
  } catch (error) {
    caught = error
  }
  assert(caught, `${label}: expected a duplicate-key error`)
  assert(
    caught.code === 'ER_DUP_ENTRY' || Number(caught.errno) === 1062,
    `${label}: expected ER_DUP_ENTRY/1062, received ${caught.code || caught.errno || 'unknown'}`
  )
}

async function createOwnedDatabase(rootConnection, databaseName, ownedDatabases) {
  assert.match(databaseName, SAFE_DATABASE_PATTERN)
  ownedDatabases.add(databaseName)
  await rootConnection.query(
    `CREATE DATABASE ${quoteIdentifier(databaseName)} CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`
  )
}

async function dropOwnedDatabase(rootConnection, config, databaseName, ownedDatabases) {
  assert.equal(config.host, EXPECTED_HOST, 'refusing DROP outside the dedicated localhost host')
  assert.equal(config.port, EXPECTED_PORT, 'refusing DROP outside the dedicated localhost port')
  assert.equal(config.allowDestructive, EXPECTED_ALLOW_DESTRUCTIVE, 'refusing DROP without explicit safety confirmation')
  assert.match(databaseName, SAFE_DATABASE_PATTERN, 'refusing DROP for an unsafe database name')
  assert(ownedDatabases.has(databaseName), 'refusing DROP for a database not generated by this process')
  await rootConnection.query(`DROP DATABASE ${quoteIdentifier(databaseName)}`)
  ownedDatabases.delete(databaseName)
}

